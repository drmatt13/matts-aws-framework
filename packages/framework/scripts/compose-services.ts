import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { parse, stringify, type CollectionTag, type ScalarTag } from "yaml";
import { getLocalTargets, resolveServiceTarget, type FrameworkConfig, type NormalizedTarget } from "../src/config/index";
import { findDockerfile, resolveServicePort, resolveServiceSourcePath } from "../src/config/source";
import { getTargetEnvironmentPrefix } from "../src/local/services";

/**
 * Local service containers, derived from their declarations.
 *
 * docker-compose.yml is authored: support infrastructure, the dev servers and
 * `x-framework-service`, the container a framework service runs in on this
 * machine. A service's own facts are already declared: its id names the
 * container the local API dev server proxies to, its directory's package.json
 * names the workspace and dev script to run, and its port and healthCheckPath
 * say where it listens and how it is probed. framework:generate joins the two
 * into docker-compose.services.yml, which docker-compose.yml includes.
 *
 * Generation never writes docker-compose.yml. A service declared there under
 * its id is the developer's, and is left out of the generated file.
 */
export const COMPOSE_FILE = "docker-compose.yml";
export const GENERATED_COMPOSE_FILE = "docker-compose.services.yml";
export const SERVICE_TEMPLATE = "x-framework-service";

const LAUNCHER = "packages/framework/scripts/run-service.ts";
const LAUNCHER_MOUNTS = ["/workspace/.framework/local", "/workspace/cdk-app/.env.dev"] as const;
const GENERATED_HEADER = "# Generated by npm run framework:generate";

type ComposeService = Record<string, unknown> & {
  readonly command?: unknown;
  readonly environment?: unknown;
  readonly volumes?: unknown;
};
export interface ComposeModel {
  readonly include?: readonly unknown[];
  readonly services?: Readonly<Record<string, ComposeService>>;
  readonly [key: string]: unknown;
}

/**
 * Compose's own tags. `!override` keeps its value; `!reset` empties one, read
 * here as the empty value it is written with (`!reset []`, `!reset null`).
 */
const COMPOSE_TAGS = ["!reset", "!override"].flatMap((tag): (ScalarTag | CollectionTag)[] => [
  { tag, resolve: (value: string) => (tag === "!reset" ? null : value) },
  { tag, collection: "map", resolve: (map) => map },
  { tag, collection: "seq", resolve: (seq) => seq },
]);

/** Reads Compose YAML the way Compose does, `<<:` merge keys included. */
export function parseCompose(text: string): ComposeModel {
  return (parse(text, { merge: true, customTags: COMPOSE_TAGS }) ?? {}) as ComposeModel;
}

/** Whether a file at this path is one framework:generate wrote, and so may replace or remove. */
export function isGeneratedCompose(text: string | undefined): boolean {
  return text?.startsWith(GENERATED_HEADER) ?? false;
}

interface DerivedService {
  readonly target: NormalizedTarget;
  readonly packageName: string;
  readonly port: number;
  readonly portOrigin: string;
  readonly healthCheckPath?: string;
}

/** What a service's container is made from, or why it cannot be made from its declaration. */
function deriveService(
  config: FrameworkConfig,
  target: NormalizedTarget,
  repositoryRoot: string,
): DerivedService | { readonly reason: string } {
  const directory = resolveServiceSourcePath(config, target.id, { repositoryRoot });
  const relative = path.relative(repositoryRoot, directory).split(path.sep).join("/");
  const manifestFile = path.join(directory, "package.json");
  if (!existsSync(manifestFile)) return { reason: `${relative} has no package.json naming a dev script to run` };
  const manifest = JSON.parse(readFileSync(manifestFile, "utf8")) as { name?: unknown; scripts?: Record<string, unknown> };
  if (typeof manifest.name !== "string") return { reason: `${relative}/package.json has no name for npm --workspace to run` };
  if (typeof manifest.scripts?.dev !== "string") {
    return { reason: `${relative}/package.json has no "dev" script, the command its container runs and Watch restarts` };
  }
  if (!isWorkspace(repositoryRoot, relative)) {
    return { reason: `${relative} is not among the root package.json workspaces, so the development image does not install it` };
  }
  const declared = resolveServiceTarget(config, target.id);
  const dockerfile = findDockerfile(directory);
  return {
    target,
    packageName: manifest.name,
    port: resolveServicePort(config, target.id, { repositoryRoot }),
    portOrigin: declared.port !== undefined ? "port" : `EXPOSE in ${relative}/${path.basename(dockerfile ?? "Dockerfile")}`,
    ...(declared.healthCheckPath === undefined ? {} : { healthCheckPath: declared.healthCheckPath }),
  };
}

function isWorkspace(repositoryRoot: string, relative: string): boolean {
  const root = JSON.parse(readFileSync(path.join(repositoryRoot, "package.json"), "utf8")) as {
    workspaces?: readonly string[] | { packages?: readonly string[] };
  };
  const patterns: readonly string[] = Array.isArray(root.workspaces)
    ? root.workspaces
    : (root.workspaces as { packages?: readonly string[] } | undefined)?.packages ?? [];
  return patterns.some((pattern) => {
    const expression = pattern
      .replace(/\/+$/, "")
      .split("/")
      .map((segment) => (segment === "**" ? ".*" : segment.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*/g, "[^/]*")))
      .join("/");
    return new RegExp(`^${expression}$`).test(relative);
  });
}

function serviceTemplate(authored: ComposeModel): Record<string, unknown> | undefined {
  const template = authored[SERVICE_TEMPLATE];
  if (template === undefined) return undefined;
  if (template === null || typeof template !== "object" || Array.isArray(template)) {
    throw new Error(
      `${COMPOSE_FILE}'s ${SERVICE_TEMPLATE} must be a service definition: the build, Watch rules, environment and mounts every generated service starts from.`,
    );
  }
  return template as Record<string, unknown>;
}

/** Compose's two spellings of an environment, as one mapping. */
function environmentOf(service: { readonly environment?: unknown } | undefined): Record<string, unknown> {
  const environment = service?.environment;
  if (Array.isArray(environment)) {
    return Object.fromEntries(
      environment.map((entry) => {
        const text = String(entry);
        const separator = text.indexOf("=");
        return separator < 0 ? [text, null] : [text.slice(0, separator), text.slice(separator + 1)];
      }),
    );
  }
  return environment && typeof environment === "object" ? { ...(environment as Record<string, unknown>) } : {};
}

function planServices(
  config: FrameworkConfig,
  authored: ComposeModel,
  repositoryRoot: string,
): { readonly generated: readonly DerivedService[]; readonly reasons: ReadonlyMap<string, string> } {
  const generated: DerivedService[] = [];
  const reasons = new Map<string, string>();
  for (const target of getLocalTargets(config, ["service"], "unconditioned")) {
    if (authored.services?.[target.id] !== undefined) continue;
    const derived = deriveService(config, target, repositoryRoot);
    if ("reason" in derived) reasons.set(target.id, derived.reason);
    else generated.push(derived);
  }
  return { generated, reasons };
}

const flow = (value: unknown): string =>
  stringify(value, { collectionStyle: "flow", flowCollectionPadding: false, lineWidth: 0 }).trimEnd();
const block = (value: unknown, indent: string): string =>
  stringify(value, { lineWidth: 0 }).trimEnd().split("\n").map((line) => `${indent}${line}`).join("\n");

/** The probe a healthCheckPath adds: a GET on the container's own port that must answer 200. */
function probe(port: number, healthCheckPath: string): readonly string[] {
  const url = `http://127.0.0.1:${port}${healthCheckPath}`.replace(/[\\']/g, "\\$&");
  return [
    "CMD",
    "node",
    "-e",
    `require('node:http').get('${url}',r=>{r.resume();process.exit(r.statusCode===200?0:1)}).on('error',()=>process.exit(1))`,
  ];
}

/**
 * docker-compose.services.yml for this config and docker-compose.yml, or
 * undefined when docker-compose.yml defines no x-framework-service to build one
 * from. Deterministic: the same declarations and template give the same bytes.
 */
export function composeServicesFile(
  config: FrameworkConfig,
  authored: ComposeModel,
  options: { readonly repositoryRoot: string },
): string | undefined {
  const template = serviceTemplate(authored);
  if (!template) return undefined;
  const { environment: _environment, healthcheck, ...shape } = template;
  const environment = environmentOf(template);
  const timing = healthcheck && typeof healthcheck === "object" ? (healthcheck as Record<string, unknown>) : undefined;
  const { generated } = planServices(config, authored, options.repositoryRoot);

  const lines = [
    `${GENERATED_HEADER} from framework.config.ts and the`,
    `# ${SERVICE_TEMPLATE} container in ${COMPOSE_FILE}, which includes this file. Do not edit it:`,
    "# generation replaces it.",
    "#",
    "# One container for each service framework.config.ts runs locally. Each is",
    `# ${SERVICE_TEMPLATE} as written, plus what its declaration decides: the container`,
    "# name (its id, which the local API dev server proxies to), the run-service",
    "# command for its workspace's dev script, PORT, and a probe of its",
    "# healthCheckPath. To change one service, add to it in",
    "# docker-compose.override.yml, which Compose merges over everything, or declare",
    `# it in ${COMPOSE_FILE} under its id; this file then leaves it out.`,
    "",
    `# ${SERVICE_TEMPLATE} from ${COMPOSE_FILE}, resolved.`,
    "x-service: &service",
    block(shape, "  "),
    "x-service-environment: &service-environment",
    block(environment, "  "),
    "",
  ];
  if (generated.length === 0) {
    lines.push("services: {}");
    return `${lines.join("\n")}\n`;
  }
  lines.push("services:");
  for (const service of generated) {
    const { target, port, healthCheckPath } = service;
    const test = healthCheckPath === undefined ? undefined : probe(port, healthCheckPath);
    // A template probe with a test of its own applies to a service that names
    // no healthCheckPath; one with timing alone only times the derived probe.
    const check = test ? { ...timing, test } : timing?.test === undefined ? undefined : timing;
    lines.push(
      `  ${target.id}:`,
      `    # ${target.origins[0] ?? target.reference}: listens on ${port} (its ${service.portOrigin}),`,
      `    # runs the dev script of ${service.packageName}${healthCheckPath === undefined ? "" : `, probed at its healthCheckPath ${healthCheckPath}`}.`,
      "    <<: *service",
      `    command: ${flow(["node", "--import", "tsx", LAUNCHER, target.id, "--", "npm", "--workspace", service.packageName, "run", "dev"])}`,
      "    environment:",
      "      <<: *service-environment",
      `      PORT: ${flow(String(port))}`,
    );
    if (check) {
      const { test: probeTest, ...rest } = check as Record<string, unknown>;
      lines.push("    healthcheck:", `      test: ${flow(probeTest)}`);
      if (Object.keys(rest).length > 0) lines.push(block(rest, "      "));
    }
  }
  return `${lines.join("\n")}\n`;
}

function includes(authored: ComposeModel, file: string): boolean {
  return (authored.include ?? []).some((entry) => {
    const paths = typeof entry === "string" ? [entry] : (entry as { path?: unknown } | null)?.path;
    return (Array.isArray(paths) ? paths : [paths]).some((candidate) => typeof candidate === "string" && path.normalize(candidate) === file);
  });
}

/**
 * Every service that runs locally has a container that can start it, before
 * any container starts: one the developer declared in docker-compose.yml, or
 * one generated into docker-compose.services.yml, which docker-compose.yml
 * includes. Either way it starts through run-service, which resolves the
 * declared environment, from the two read-only mounts it reads, and with the
 * PORT the local API dev server sends its requests to.
 */
export function assertLocalServiceContainers(
  config: FrameworkConfig,
  authored: ComposeModel,
  generatedText: string | undefined,
  options: { readonly repositoryRoot: string },
): void {
  const generated = generatedText === undefined ? {} : parseCompose(generatedText).services ?? {};
  const included = includes(authored, GENERATED_COMPOSE_FILE);
  const services = { ...(included ? generated : {}), ...authored.services };
  const { reasons } = planServices(config, authored, options.repositoryRoot);
  for (const target of getLocalTargets(config, ["service"], "unconditioned")) {
    const service = services[target.id];
    if (!service) {
      if (generated[target.id]) {
        throw new Error(
          `${COMPOSE_FILE} does not include ${GENERATED_COMPOSE_FILE}, so service:${target.id}'s generated container never starts. Add to ${COMPOSE_FILE}:\n  include:\n    - ${GENERATED_COMPOSE_FILE}`,
        );
      }
      const reason = reasons.get(target.id);
      throw new Error(
        reason && serviceTemplate(authored)
          ? `service:${target.id} runs locally, and its container cannot be generated: ${reason}. Fix that, or declare a service named "${target.id}" in ${COMPOSE_FILE}.`
          : `service:${target.id} runs locally and has no container. Declare a service named "${target.id}" in ${COMPOSE_FILE}, or define ${SERVICE_TEMPLATE} there and include ${GENERATED_COMPOSE_FILE}, and framework:generate writes one (docs/FRAMEWORK.md, Local service containers).`,
      );
    }
    if (!Array.isArray(service.command) || !service.command.includes(LAUNCHER) || !service.command.includes(target.id)) {
      throw new Error(`service:${target.id} must start through ${LAUNCHER} <id> -- <command>.`);
    }
    for (const location of LAUNCHER_MOUNTS) {
      const volumes = Array.isArray(service.volumes) ? (service.volumes as { target?: string; read_only?: boolean }[]) : [];
      if (!volumes.some((mount) => mount?.target === location && mount.read_only)) {
        throw new Error(`service:${target.id} needs a read-only mount of ${location}.`);
      }
    }
    // The local API dev server proxies to http://<id>:<resolved port> unless a
    // container overrides that address with <ID>_SERVICE_URL, so a PORT that
    // disagrees with the declaration is a service nothing reaches.
    const port = environmentOf(service).PORT;
    const variable = `${getTargetEnvironmentPrefix(target.id)}_SERVICE_URL`;
    const redirected = Object.values(services).some((other) => environmentOf(other)[variable] !== undefined);
    const resolved = resolveServicePort(config, target.id, options);
    if (port !== undefined && port !== null && String(port) !== String(resolved) && !redirected) {
      throw new Error(
        `${COMPOSE_FILE} gives service:${target.id} PORT ${String(port)}, but it declares port ${resolved}, where the local API dev server sends its requests. Remove PORT (run-service sets it from the declaration) or set it to ${resolved}.`,
      );
    }
  }
}
