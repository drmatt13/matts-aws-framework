import { createRequire } from "node:module";
import path from "node:path";

/**
 * The services an interface VPC endpoint can reach, as the CDK the application
 * deploys with knows them.
 *
 * Read from cdk-app's aws-cdk-lib rather than a copy of AWS's list, so the
 * names `interfaceEndpoints` completes are exactly the ones `NetworkStack` can
 * build, and a CDK upgrade that adds a service shows up as a stale generated
 * file instead of a silently missing name. @repo/framework stays free of a CDK
 * dependency: the library is resolved from cdk-app, which owns it.
 */
export function vpcEndpointServicesModule(repositoryRoot: string): string {
  const cdkRequire = createRequire(path.join(repositoryRoot, "cdk-app", "package.json"));
  const { version } = cdkRequire("aws-cdk-lib/package.json") as { version: string };
  const { InterfaceVpcEndpointAwsService: services } = cdkRequire("aws-cdk-lib/aws-ec2") as {
    InterfaceVpcEndpointAwsService: Function & Record<string, unknown>;
  };
  const names = new Set<string>();
  for (const key of Object.getOwnPropertyNames(services)) {
    const service = services[key];
    if (!(service instanceof services)) continue;
    const { shortName } = service as { shortName: string };
    if (!/^[a-z0-9][a-z0-9.-]*$/.test(shortName)) {
      throw new Error(`aws-cdk-lib ${version} names an interface endpoint service ${JSON.stringify(shortName)}, which is not an endpoint name.`);
    }
    names.add(shortName);
  }
  // network.ts reaches these two through its gateway endpoints, which are free.
  names.delete("s3");
  names.delete("dynamodb");
  if (names.size === 0) throw new Error(`aws-cdk-lib ${version} lists no interface endpoint services.`);

  return `/* This file is generated by npm run framework:generate. Do not edit. */

/**
 * Every AWS service an interface VPC endpoint reaches, by the name AWS gives
 * its endpoint (com.amazonaws.<region>.<name>), as aws-cdk-lib ${version} lists
 * them. S3 and DynamoDB are left out: network.ts reaches them through its free
 * gateway endpoints instead.
 */
export const INTERFACE_ENDPOINT_SERVICES = [
${[...names].sort().map((name) => `  ${JSON.stringify(name)},`).join("\n")}
] as const;
`;
}
