import { buttonClasses } from "../ui/Button";
import { cx } from "../ui/classes";
import { authorizationLabel, type ConnectionAuthorization } from "../../shared/permissions";
import { useStudio } from "../studio";

export function AuthorizationBadge({ authorization }: { readonly authorization?: ConnectionAuthorization }) {
  return authorization ? <span className={cx("inline-flex items-center w-fit p-[2px_6px] border border-rule-strong rounded-sm [font:600_10px_var(--sans)] [letter-spacing:.035em] whitespace-nowrap text-graphite", authorization.kind === "iam" && "text-ink")} data-slot="authorization-badge">{authorizationLabel(authorization)}</span> : null;
}

/** Declaration evidence, with the principal shown independently of the graph arrow. */
export function AuthorizationDetails({ authorization }: { readonly authorization: ConnectionAuthorization }) {
  const { select } = useStudio();
  return <div className={"m-[14px_0]"} data-slot="authorization-details">
    <div className={"flex [gap:10px] items-center flex-wrap [&_h3]:m-0"} data-slot="authorization-heading"><h3>Authorization</h3><AuthorizationBadge authorization={authorization} /></div>
    {authorization.kind === "iam" && authorization.state === "not-built" ? <p className={"text-step-minus1 [border-left:2px_solid_var(--local)] [padding-left:10px]"} data-slot="authorization-status">Applies when this workload runs in AWS.</p> : null}
    {authorization.grants.map((grant, index) => <dl className={"m-[10px_0] p-[10px_12px] [border-left:2px_solid_var(--rule-strong)] bg-wash text-step-minus1 [&>div]:m-[0_0_8px] [&>div:last-child]:mb-0 [&_dt]:text-graphite [&_dt]:text-meta [&_dd]:m-[2px_0_0] [&_dd]:wrap-anywhere"} key={index} data-slot="authorization-grant">
      <div><dt>Principal</dt><dd>{grant.principalEntity ? <button className={buttonClasses({ variant: "link" })} onClick={() => select(grant.principalEntity!)}>{grant.principal}</button> : grant.principal}</dd></div>
      <div><dt>Policy</dt><dd>{grant.policy}</dd></div>
      {grant.actions ? <div><dt>Actions</dt><dd><code>{grant.actions.join(", ")}</code></dd></div> : null}
      {grant.via ? <div><dt>Generated by</dt><dd><code>{grant.via}</code></dd></div> : null}
      <div><dt>Scope</dt><dd>{grant.scope}</dd></div>
      {grant.conditions?.length ? <div><dt>Conditions</dt><dd>{grant.conditions.join("; ")}</dd></div> : null}
    </dl>)}
    {authorization.notes.map(note => <p key={note} className={"text-caption text-graphite"}>{note}</p>)}
    {authorization.kind === "iam" ? <p className={"text-caption text-graphite"}>Derived from source declarations. Synthesis expands native grants; deployed policies and effective access are not verified here.</p> : null}
  </div>;
}
