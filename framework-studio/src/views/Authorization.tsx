import { authorizationLabel, type ConnectionAuthorization } from "../../shared/permissions";
import { useStudio } from "../studio";

export function AuthorizationBadge({ authorization }: { readonly authorization?: ConnectionAuthorization }) {
  return authorization ? <span className={`authorization-badge ${authorization.kind}`}>{authorizationLabel(authorization)}</span> : null;
}

/** Declaration evidence, with the principal shown independently of the graph arrow. */
export function AuthorizationDetails({ authorization }: { readonly authorization: ConnectionAuthorization }) {
  const { select } = useStudio();
  return <div className="authorization-details">
    <div className="authorization-heading"><h3>Authorization</h3><AuthorizationBadge authorization={authorization} /></div>
    {authorization.state === "not-built" ? <p className="authorization-status">Cloud intent only. These permissions are not generated in the AWS graph being viewed.</p> : null}
    {authorization.grants.map((grant, index) => <dl className="authorization-grant" key={index}>
      <div><dt>Principal</dt><dd>{grant.principalEntity ? <button className="linkish" onClick={() => select(grant.principalEntity!)}>{grant.principal}</button> : grant.principal}</dd></div>
      <div><dt>Policy</dt><dd>{grant.policy}</dd></div>
      {grant.actions ? <div><dt>Actions</dt><dd><code>{grant.actions.join(", ")}</code></dd></div> : null}
      {grant.via ? <div><dt>Generated by</dt><dd><code>{grant.via}</code></dd></div> : null}
      <div><dt>Scope</dt><dd>{grant.scope}</dd></div>
      {grant.conditions?.length ? <div><dt>Conditions</dt><dd>{grant.conditions.join("; ")}</dd></div> : null}
    </dl>)}
    {authorization.notes.map(note => <p key={note} className="small muted">{note}</p>)}
    {authorization.kind === "iam" ? <p className="small muted">Derived from source declarations. Synthesis expands native grants; deployed policies and effective access are not verified here.</p> : null}
  </div>;
}
