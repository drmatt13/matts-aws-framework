import { buttonClasses } from "../ui/Button";
import { cx } from "../ui/classes";
import { authorizationLabel, type ConnectionAuthorization } from "../../shared/permissions";
import { useStudio } from "../studio";

export function AuthorizationBadge({
  authorization,
  className,
}: {
  readonly authorization?: ConnectionAuthorization;
  readonly className?: string;
}) {
  return authorization ? (
    <span
      className={cx(
        "inline-flex w-fit items-center rounded-sm border border-rule-strong px-1.5 py-0.5 font-sans text-[10px] font-semibold leading-[normal] tracking-[.035em] whitespace-nowrap",
        authorization.kind === "iam" ? "text-ink" : "text-graphite",
        className,
      )}
      data-slot="authorization-badge"
    >
      {authorizationLabel(authorization)}
    </span>
  ) : null;
}

/** Declaration evidence, with the principal shown independently of the graph arrow. */
export function AuthorizationDetails({
  authorization,
}: {
  readonly authorization: ConnectionAuthorization;
}) {
  const { select } = useStudio();
  return (
    <div className="my-3.5" data-slot="authorization-details">
      <div className="flex flex-wrap items-center gap-2.5" data-slot="authorization-heading">
        <h3 className="m-0 text-label font-semibold text-balance">Authorization</h3>
        <AuthorizationBadge authorization={authorization} />
      </div>
      {authorization.kind === "iam" && authorization.state === "not-built" ? (
        <p
          className="mt-0 mb-2 border-l-2 border-local pl-2.5 text-step-minus1"
          data-slot="authorization-status"
        >
          Applies when this workload runs in AWS.
        </p>
      ) : null}
      {authorization.grants.map((grant, index) => (
        <dl
          className="my-2.5 border-l-2 border-rule-strong bg-wash px-3 py-2.5 text-step-minus1"
          key={index}
          data-slot="authorization-grant"
        >
          <div className="mb-2 last:mb-0">
            <dt className="text-meta text-graphite">Principal</dt>
            <dd className="mx-0 mt-0.5 mb-0 wrap-anywhere">
              {grant.principalEntity ? (
                <button
                  className={buttonClasses({ variant: "link" })}
                  onClick={() => select(grant.principalEntity!)}
                >
                  {grant.principal}
                </button>
              ) : (
                grant.principal
              )}
            </dd>
          </div>
          <div className="mb-2 last:mb-0">
            <dt className="text-meta text-graphite">Policy</dt>
            <dd className="mx-0 mt-0.5 mb-0 wrap-anywhere">{grant.policy}</dd>
          </div>
          {grant.actions ? (
            <div className="mb-2 last:mb-0">
              <dt className="text-meta text-graphite">Actions</dt>
              <dd className="mx-0 mt-0.5 mb-0 wrap-anywhere">
                <code>{grant.actions.join(", ")}</code>
              </dd>
            </div>
          ) : null}
          {grant.via ? (
            <div className="mb-2 last:mb-0">
              <dt className="text-meta text-graphite">Generated by</dt>
              <dd className="mx-0 mt-0.5 mb-0 wrap-anywhere">
                <code>{grant.via}</code>
              </dd>
            </div>
          ) : null}
          <div className="mb-2 last:mb-0">
            <dt className="text-meta text-graphite">Scope</dt>
            <dd className="mx-0 mt-0.5 mb-0 wrap-anywhere">{grant.scope}</dd>
          </div>
          {grant.conditions?.length ? (
            <div className="mb-2 last:mb-0">
              <dt className="text-meta text-graphite">Conditions</dt>
              <dd className="mx-0 mt-0.5 mb-0 wrap-anywhere">{grant.conditions.join("; ")}</dd>
            </div>
          ) : null}
        </dl>
      ))}
      {authorization.notes.map((note) => (
        <p key={note} className="mt-0 mb-2 text-caption text-graphite">
          {note}
        </p>
      ))}
      {authorization.kind === "iam" ? (
        <p className="mt-0 mb-2 text-caption text-graphite">
          Derived from source declarations. Synthesis expands native grants; deployed policies and
          effective access are not verified here.
        </p>
      ) : null}
    </div>
  );
}
