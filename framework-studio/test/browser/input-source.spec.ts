import type { ModelResource } from "../../shared/model";
import type { ResourceIntent } from "../../shared/resources";
import { test, expect, assertAccessible } from "./support/test";

for (const width of [1440, 390]) test(`input source and creator switches preserve values and reviewed intent at ${width}px`, async ({ page, studio }) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width, height: 1000 });
  const standalone: ModelResource = { id: "resource:standalone", path: ["standalone"], kind: "input", absent: false, authoredValue: "alpha",
    modes: { dev: { present: true, required: false, value: "alpha" }, prod: { present: true, required: false, value: "alpha" } } };
  const linked: ModelResource = { id: "resource:linked", path: ["linked"], kind: "input", absent: false, fromEnv: "LINKED_INPUT", values: ["alpha", "beta"],
    modes: { dev: { present: true, required: false }, prod: { present: true, required: false } } };
  for (const model of Object.values(studio.response.snapshot.models)) Object.assign(model, { resources: [...model.resources, standalone, linked] });
  studio.reply("GET", "/api/resources/details", async route => { await route.fulfill({ json: { configured: false, file: "cdk-app/.env.dev", inputFile: { exists: true, hash: "browser-inputs" } } }); });
  studio.reply("POST", "/api/resources/plan", async route => {
    const { intent } = route.request().postDataJSON() as { intent: ResourceIntent };
    await route.fulfill({ json: { planId: "input-source-plan", resource: intent.resource, nextResource: intent.resource, ok: true, changes: [], diagnostics: [] } });
  });
  await studio.goto("/?select=resource%3Astandalone");
  const inspector = page.getByRole("complementary", { name: "Inspector", exact: true });
  const source = inspector.getByRole("switch", { name: "Link to .env file", exact: true });
  const review = inspector.getByRole("button", { name: "Review Changes", exact: true });
  await expect(source).toHaveAttribute("aria-checked", "false");
  await expect(inspector.getByRole("region", { name: "Local value", exact: true })).toHaveCount(0);
  await expect(inspector.getByText(/Saves to cdk-app/)).toHaveCount(0);
  await expect(inspector.getByRole("textbox", { name: "Environment variable", exact: true })).toHaveCount(0);
  expect(studio.requests.filter(request => request.path.startsWith("/api/resources/details"))).toHaveLength(0);
  await inspector.getByRole("textbox", { name: "Value in development", exact: true }).fill("");
  await expect(review).toBeDisabled();
  await inspector.getByRole("textbox", { name: "Value in development", exact: true }).fill("beta");
  await inspector.getByRole("textbox", { name: "Value in production", exact: true }).fill("beta");
  await source.focus();
  await page.keyboard.press("Space");
  await expect(inspector.getByRole("textbox", { name: "Default in development", exact: true })).toHaveValue("beta");
  await expect(inspector.getByRole("textbox", { name: "Default in production", exact: true })).toHaveValue("beta");
  await source.click();
  await expect(inspector.getByRole("textbox", { name: "Value in development", exact: true })).toHaveValue("beta");
  await review.click();
  let plan = studio.requests.filter(request => request.path === "/api/resources/plan").at(-1)!.body as { intent: ResourceIntent };
  expect(plan.intent.fromEnv).toBeNull();
  expect(plan.intent.modes.dev).toMatchObject({ default: null, value: "beta" });
  await page.getByRole("dialog").getByRole("button", { name: "Back to Editing", exact: true }).click();
  await expect(inspector.getByRole("textbox", { name: "Value in development", exact: true })).toHaveValue("beta");
  await source.click();
  await inspector.getByRole("textbox", { name: "Environment variable", exact: true }).fill("");
  await expect(review).toBeDisabled();
  await inspector.getByRole("textbox", { name: "Environment variable", exact: true }).fill("STANDALONE_OVERRIDE");
  await source.click();
  await expect(inspector.getByRole("textbox", { name: "Value in development", exact: true })).toHaveValue("beta");
  await source.click();
  await expect(inspector.getByRole("textbox", { name: "Environment variable", exact: true })).toHaveValue("STANDALONE_OVERRIDE");
  await inspector.getByRole("textbox", { name: "Default in development", exact: true }).fill("");
  await inspector.getByRole("textbox", { name: "Default in production", exact: true }).fill("");
  await expect(review).toBeEnabled();
  await review.click();
  plan = studio.requests.filter(request => request.path === "/api/resources/plan").at(-1)!.body as { intent: ResourceIntent };
  expect(plan.intent.fromEnv).toBe("STANDALONE_OVERRIDE");
  expect(plan.intent.modes.dev.default).toBeNull();
  expect(plan.intent.modes.dev.value).toBeUndefined();
  await page.getByRole("dialog").getByRole("button", { name: "Back to Editing", exact: true }).click();
  await inspector.getByRole("button", { name: "Discard", exact: true }).click();
  await inspector.getByRole("button", { name: "Back to Resources", exact: true }).click();
  await page.locator('[data-resource-id="resource:linked"]').click();
  await expect(inspector.getByRole("region", { name: "Local value", exact: true })).toBeVisible();
  const defaultChoice = inspector.getByRole("combobox", { name: "Default in development", exact: true });
  await defaultChoice.selectOption("alpha");
  await source.click();
  await expect(inspector.getByRole("combobox", { name: "Value in development", exact: true })).toHaveValue("alpha");
  await expect(review).toBeDisabled(); // Production needs its standalone value too.
  await inspector.getByRole("combobox", { name: "Value in production", exact: true }).selectOption("beta");
  await expect(review).toBeEnabled();
  await assertAccessible(page);
  await inspector.getByRole("button", { name: "Discard", exact: true }).click();
  await inspector.getByRole("button", { name: "Close panel", exact: true }).click();

  await page.getByRole("button", { name: "Add to application", exact: true }).click();
  await page.getByRole("dialog", { name: "Add to application", exact: true }).getByRole("button", { name: "Input parameter or secret", exact: true }).click();
  const creator = page.getByRole("dialog", { name: "Create input parameter or secret", exact: true });
  await creator.getByRole("textbox", { name: "Stable identifier", exact: true }).fill("createdInput");
  const createReview = creator.getByRole("button", { name: "Review generated changes", exact: true });
  await expect(creator.getByRole("textbox", { name: "Default value (optional)", exact: true })).toHaveValue("");
  await expect(createReview).toBeEnabled();
  await createReview.click();
  let batch = studio.requests.filter(request => request.path === "/api/edits/batch/plan").at(-1)!.body as { edits: { request: Record<string, unknown> }[] };
  expect(batch.edits[0]!.request).toMatchObject({ kind: "input", linkedToEnv: true, defaultValue: "" });
  await page.getByRole("dialog").getByRole("button", { name: "Back to Editing", exact: true }).click();
  await creator.getByRole("textbox", { name: "Default value (optional)", exact: true }).fill("creator-value");
  await creator.getByRole("switch", { name: "Link to .env file", exact: true }).click();
  await expect(creator.getByRole("textbox", { name: "Value", exact: true })).toHaveValue("creator-value");
  await expect(creator.getByRole("textbox", { name: "Environment variable", exact: true })).toHaveCount(0);
  await expect(creator.getByRole("switch", { name: "Required for every enabled consumer", exact: true })).toHaveCount(0);
  await expect(creator.getByRole("textbox", { name: "Default value (optional)", exact: true })).toHaveCount(0);
  await creator.getByRole("switch", { name: "Secret", exact: true }).click();
  await expect(creator.getByRole("textbox", { name: "Environment variable", exact: true })).toBeVisible();
  await expect(creator.getByRole("textbox", { name: "Value", exact: true })).toHaveCount(0);
  await creator.getByRole("switch", { name: "Secret", exact: true }).click();
  await expect(creator.getByRole("switch", { name: "Link to .env file", exact: true })).toHaveAttribute("aria-checked", "false");
  await expect(creator.getByRole("textbox", { name: "Value", exact: true })).toHaveValue("creator-value");
  await createReview.click();
  batch = studio.requests.filter(request => request.path === "/api/edits/batch/plan").at(-1)!.body as { edits: { request: Record<string, unknown> }[] };
  expect(batch.edits[0]!.request).toMatchObject({ kind: "input", linkedToEnv: false, value: "creator-value" });
  expect(batch.edits[0]!.request.envName).toBe(""); // The legacy request field is sanitized; no variable survives.
  await page.getByRole("dialog").getByRole("button", { name: "Back to Editing", exact: true }).click();
  await expect(creator.getByRole("textbox", { name: "Value", exact: true })).toHaveValue("creator-value");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await assertAccessible(page);
  await creator.getByRole("button", { name: "Cancel creation", exact: true }).click();
  expect(studio.requests.filter(request => /apply$/.test(request.path))).toHaveLength(0);
});
